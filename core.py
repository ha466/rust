"""core.py - shared config, data models, constants, logging and the OpenAI client.

Everything the other modules have in common lives here:

* ``Config``      - every setting of the pipeline in one dataclass
* ``Chunk``       - one small piece of code (a function, a struct, ...)
* ``RepoMeta``    - information about a cloned repository
* ``LLMClient``   - thin async wrapper around any OpenAI-compatible endpoint
"""
from __future__ import annotations

import hashlib
import logging
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

log = logging.getLogger("rustset")

# --------------------------------------------------------------------------- #
# Constants
# --------------------------------------------------------------------------- #
